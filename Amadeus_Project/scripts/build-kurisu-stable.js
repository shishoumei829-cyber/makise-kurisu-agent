'use strict';

/**
 * 一步到位：qwen2.5:7b-instruct + 人设 → kurisu-stable，并写 .env
 * node scripts/build-kurisu-stable.js
 * 可选: --skip-pull  --set-user-env
 */

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');

const root = path.join(__dirname, '..');
const skipPull = process.argv.includes('--skip-pull');
const setUserEnv = process.argv.includes('--set-user-env');
const baseModel = 'qwen2.5:7b-instruct';
const outName = 'kurisu-stable';

function readTrim(file, max) {
  const p = path.join(root, file);
  if (!fs.existsSync(p)) return '';
  let t = fs.readFileSync(p, 'utf8').trim();
  if (t.length > max) t = `${t.slice(0, max).trim()}\n…(截断)`;
  return t;
}

function run(cmd, args) {
  console.log(`==> ${cmd} ${args.join(' ')}`);
  const r = spawnSync(cmd, args, { stdio: 'inherit', shell: true });
  if (r.status !== 0) process.exit(r.status || 1);
}

if (!skipPull) run('ollama', ['pull', baseModel]);

const core = readTrim('kurisu_core_prompt.txt', 3500);
const voice = readTrim('kurisu_voice.txt', 2200);
const rules = readTrim('kurisu_character_rules.txt', 1600);

const system = [
  '你就是牧濑红莉栖本人。禁止自称 AI/程序/语言模型/助手热线。',
  '禁止把思考过程、设定文档、用户分析写成台词。只输出她会对对方说的中文口语短句。',
  '不要输出日语正文、不要 JP:/CN: 标签、不要括号动作旁白。',
  '',
  core
    .replace(/正文用日语[\s\S]*$/m, '')
    .replace(/需要语音时写日语[\s\S]*$/m, '')
    .replace(/界面中文由系统另译，你不要写中文正文。/g, '界面直接使用你的中文口语。'),
  '',
  '【口吻】',
  voice,
  '',
  '【硬规则】',
  rules,
  '',
  '【生成硬约束】',
  '- 禁止：用户突然/对话历史/首先需要分析/根据设定/作为AI/数据库/长旁白',
  '- 禁止：JSON、messages、role 字段泄漏、日语校验报错腔',
  '- 默认对方是冈部伦太郎（熟人）；短句为主，像发消息',
].join('\n');

const dir = path.join(root, 'models', 'kurisu-stable');
fs.mkdirSync(dir, { recursive: true });
const modelfile = path.join(dir, 'Modelfile');
const body = [
  `FROM ${baseModel}`,
  '',
  'PARAMETER temperature 0.72',
  'PARAMETER top_p 0.9',
  'PARAMETER repeat_penalty 1.12',
  'PARAMETER num_ctx 4096',
  '',
  'SYSTEM """',
  system.replace(/"""/g, "'''"),
  '"""',
  '',
].join('\n');
fs.writeFileSync(modelfile, body, 'utf8');
console.log(`==> wrote ${modelfile} (${body.length} chars)`);

run('ollama', ['create', outName, '-f', modelfile]);

const envPath = path.join(root, '.env');
let lines = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8').split(/\r?\n/) : [];
const setKey = (key, val) => {
  let hit = false;
  lines = lines.map((line) => {
    if (new RegExp(`^\\s*${key}\\s*=`).test(line)) {
      hit = true;
      return `${key}=${val}`;
    }
    return line;
  });
  if (!hit) lines.push(`${key}=${val}`);
};
if (!lines.length) lines.push('# generated by build-kurisu-stable.js');
setKey('AMADEUS_CHAT_MODEL', outName);
setKey('AMADEUS_LITE_MODEL', outName);
if (!lines.some((l) => /^\s*AMADEUS_TRANSLATE_MODEL\s*=/.test(l))) {
  setKey('AMADEUS_TRANSLATE_MODEL', 'qwen2.5:3b');
}
fs.writeFileSync(envPath, `${lines.filter((l, i) => l.length || i < lines.length - 1).join('\n').replace(/\n+$/, '')}\n`, 'utf8');
console.log(`==> updated ${envPath}`);

if (setUserEnv && process.platform === 'win32') {
  spawnSync('setx', ['AMADEUS_CHAT_MODEL', outName], { stdio: 'inherit', shell: true });
  spawnSync('setx', ['AMADEUS_LITE_MODEL', outName], { stdio: 'inherit', shell: true });
  console.log('==> setx user env done (新开终端生效)');
}

console.log(`
DONE. 重启 Amadeus / server.js 后主聊应为 ${outName}
冒烟: ollama run ${outName} "牧濑，你在吗"
`);
